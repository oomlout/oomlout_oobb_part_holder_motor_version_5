"""Refresh both-family measurements, archive checks and a visual comparison index."""
import csv
import hashlib
import json
from pathlib import Path
import shutil

import servo_v2
import servo_micro_v2
import working_oomp_populate

ROOT=Path(__file__).resolve().parent


def main():
    target=ROOT/'source_file/servo_comparison'
    target.mkdir(parents=True,exist_ok=True)
    fields=['family','profile','body_length','body_width','modelled_case_height',
        'ear_thickness','mount_pitch_x','mount_pitch_y','spline_teeth','spline_diameter',
        'case_top','spline_bottom','spline_top','runner_face','centre_bore_diameter',
        'screw_nominal_envelope','screw_head_well','head_seat_z','source','status','screw_evidence']
    rows=[];assemblies={}
    for family,design in [('standard',servo_v2),('micro',servo_micro_v2)]:
        data=design.reference();d=design.dimensions()
        assemblies[family]=dict(dimensions=d,footprint_mm=[74 if family=='standard' else 59,44],
            fixed_block_height_mm=round(d['assembly_top']-d['shell_bottom'],3),
            top_grid_nuts=sum(s['embedded_nut'] for s in design.grid_layout('retainer')),
            bottom_grid_passages=sum(s['included'] for s in design.grid_layout('bottom')))
        for key,p in data['profiles'].items():
            if family=='standard':
                p=design.installed_profile(key)
            r=p['retention']
            rows.append(dict(zip(fields,[family,key,*p['body'],p['tab_thickness'],*p['mount_pitch'],
                p['spline_teeth'],p['spline_diameter'],p['case_top'],p['spline_bottom'],p['spline_top'],
                p.get('runner_face',d['face']),r['clearance_diameter'],r['nominal_diameter'],
                r['head_clearance_diameter'],round(p['spline_top']+r['seat_above_spline'],3),p['source'],p['status'],r['evidence']])))
    with (target/'servo_profiles.csv').open('w',encoding='utf-8',newline='') as f:
        writer=csv.DictWriter(f,fieldnames=fields);writer.writeheader();writer.writerows(rows)
    (target/'assemblies.json').write_text(json.dumps(assemblies,indent=2),encoding='utf-8')
    archive=ROOT/'source_file/servo_micro_v2_reference'
    manifest=json.loads((archive/'downloads.json').read_text(encoding='utf-8'))
    checks=[dict(file=r['file'],passed=(archive/r['file']).exists() and
        hashlib.sha256((archive/r['file']).read_bytes()).hexdigest()==r['sha256']) for r in manifest if 'sha256' in r]
    assert all(r['passed'] for r in checks),checks
    (target/'archive_check.json').write_text(json.dumps(dict(passed=True,checked=len(checks),files=checks),indent=2),encoding='utf-8')
    option=next(o for o in working_oomp_populate.get_options() if o['oobb_name']=='holder_motor_servo_micro_v2')
    working_oomp_populate.apply_taxonomy(option)
    path='../../parts/'+working_oomp_populate.build_oomp_id(option)+'/'
    images=['comparison_standard_micro','comparison_standard_micro_sections','comparison_socket_sections',
        'comparison_retention_screws','comparison_servo_envelopes','comparison_mount_patterns',
        'comparison_rotor_profiles','3dpr','horn_fit_test','bearing_fit_test','retention_bore_test']
    text='# Servo V2 comparisons\n\nGenerated by `python make_servo_comparison.py`.\n\n'
    text+='Ten editable clearance references: four standard and six micro.\n'
    text+='[Numerical comparison](servo_profiles.csv) | [Block dimensions](assemblies.json)\n\n'
    text+='Screw values are clearance envelopes; read the evidence column before selecting hardware.\n\n'
    text+='Axial coordinates use the installed holder datum: standard includes its default 1 mm ear spacers; micro uses no ear spacers. Raw research JSON retains the nominal ear datum.\n\n'
    for name in images:
        text+=f'## {name.replace("_"," ")}\n\n![{name}]({path}{name}.png)\n\n[SCAD]({path}{name}.scad) | [STL]({path}{name}.stl)\n\n'
    (target/'README.md').write_text(text,encoding='utf-8')
    reports={}
    for family,directory in [('standard','servo_v2_clearance'),('micro','servo_micro_v2_clearance'),('shared','servo_shared_clearance')]:
        report=ROOT/'outputs'/directory/'report.json'
        if report.exists():
            data=json.loads(report.read_text(encoding='utf-8'))
            reports[family]=dict(passed=data['passed'],checks=data['checks'],report=str(report))
    summary=dict(passed=len(reports)==3 and all(r['passed'] for r in reports.values()),
                 checks=sum(r['checks'] for r in reports.values()),reports=reports)
    (target/'validation_summary.json').write_text(json.dumps(summary,indent=2),encoding='utf-8')
    if summary['passed']:
        for family,directory in [('standard','servo_v2_clearance'),('micro','servo_micro_v2_clearance')]:
            option=next(o for o in working_oomp_populate.get_options() if o['oobb_name']==f'holder_motor_servo_{family}_v2')
            working_oomp_populate.apply_taxonomy(option)
            taxonomy=[option[f'taxonomy_{i}'] for i in range(1,16) if option[f'taxonomy_{i}']]
            folders=[ROOT/'parts'/working_oomp_populate.build_oomp_id(option),
                     ROOT/'navigation_oobb'/Path(*taxonomy)]
            for folder in folders:
                if folder.is_dir():
                    shutil.copy2(ROOT/'outputs'/directory/'report.json',folder/'validation.json')
                    shutil.copy2(ROOT/'outputs/servo_shared_clearance/report.json',folder/'validation_shared.json')
    print(f'Compared {len(rows)} profiles; verified {len(checks)} archived source files.')


if __name__=='__main__':
    main()
